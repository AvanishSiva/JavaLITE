
import hashlib

import tree_sitter_java as tsjava
from tree_sitter import Language, Parser


GENERATED = {"@generated", "do not edit", "auto-generated", "autogenerated", "generated by"}
_parser = Parser(Language(tsjava.language()))

def keep(row):
    c = row["content"]

    if not (200 <= row["size"] <= 100_000):
        return False, "size"
    if row["max_line_length"] > 1000:
        return False, "long_line"
    if row["avg_line_length"] > 100:
        return False, "avg_line"
    if row["alphanum_fraction"] < 0.25:
        return False, "symbols"
    if any(g in c[:2000].lower() for g in GENERATED):
        return False, "generated"
    return True, "ok"

def parser(code):
    tree = _parser.parse(code.encode("utf8"))
    return not tree.root_node.has_error

def split_of(repo):
    h = int(hashlib.md5(repo.encode("utf-8")).hexdigest(), 16) % 100
    return "test" if h == 0 else "val" if h == 1 else "train"

